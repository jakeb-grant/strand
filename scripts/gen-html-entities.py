#!/usr/bin/env python3
"""(doc-formats) Generates crates/strand-scene/src/markup/entities.rs, the
HTML named character references both `markup:` levels decode, from the
WHATWG table:

    curl -sSo entities.json https://html.spec.whatwg.org/entities.json
    python3 scripts/gen-html-entities.py entities.json \
        > crates/strand-scene/src/markup/entities.rs

Only the names that end in `;` are kept: the legacy forms without one
(`&copy`) would turn `?a=1&copy=2` in a notification body into ©
(decisions.md, doc-formats). The table is packed for the wasm build: one
string of sorted names, their end offsets, and one u32 per name holding
its first code point (21 bits) and an index into SECOND for the second.
"""

import json
import sys


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit("usage: gen-html-entities.py entities.json")
    with open(sys.argv[1], encoding="utf-8") as f:
        table = json.load(f)
    entries = []
    for key, value in table.items():
        if not (key.startswith("&") and key.endswith(";")):
            continue
        name = key[1:-1]
        cps = value["codepoints"]
        if not 1 <= len(cps) <= 2 or not name.isascii() or not name.isalnum():
            sys.exit(f"unexpected entity {key!r}: {cps}")
        entries.append((name.encode("ascii"), cps))
    entries.sort()
    seconds = sorted({cps[1] for _, cps in entries if len(cps) == 2})
    if len(seconds) > 15:
        sys.exit("too many second code points for four bits")
    names = b"".join(n for n, _ in entries)
    if len(names) > 0xFFFF:
        sys.exit("names do not fit u16 offsets")
    ends = []
    codes = []
    at = 0
    for name, cps in entries:
        at += len(name)
        ends.append(at)
        second = seconds.index(cps[1]) + 1 if len(cps) == 2 else 0
        if cps[0] >= 1 << 21:
            sys.exit(f"code point out of range in {name!r}")
        codes.append(cps[0] | second << 21)
    longest = max(len(n) for n, _ in entries)

    out = sys.stdout
    out.write("// @generated by scripts/gen-html-entities.py from the WHATWG\n")
    out.write("// entities.json; do not edit by hand.\n")
    out.write("//\n")
    out.write(f"// {len(entries)} named character references ending in `;`.\n\n")
    out.write(f"/// The longest name, in bytes.\npub(super) const LONGEST: usize = {longest};\n\n")
    out.write("/// The names, sorted by bytes, concatenated.\n")
    out.write("pub(super) const NAMES: &str = concat!(\n")
    line = ""
    for name, _ in entries:
        piece = name.decode("ascii")
        if len(line) + len(piece) > 88:
            out.write(f'    "{line}",\n')
            line = ""
        line += piece
    if line:
        out.write(f'    "{line}",\n')
    out.write(");\n\n")
    out.write("/// Where each name ends in [`NAMES`].\n")
    write_array(out, "ENDS", "u16", ends)
    out.write("/// Each name's first code point (low 21 bits) and its second, as an\n")
    out.write("/// index into [`SECOND`] plus one (0 for none), above them.\n")
    write_array(out, "CODES", "u32", codes)
    out.write("/// The second code points some names carry.\n")
    write_array(out, "SECOND", "u32", seconds)


def write_array(out, name: str, ty: str, values: list) -> None:
    out.write(f"pub(super) const {name}: [{ty}; {len(values)}] = [\n")
    row = []
    for v in values:
        row.append(f"{v},")
        if len(" ".join(row)) > 84:
            out.write("    " + " ".join(row[:-1]) + "\n")
            row = row[-1:]
    if row:
        out.write("    " + " ".join(row) + "\n")
    out.write("];\n\n")


if __name__ == "__main__":
    main()
