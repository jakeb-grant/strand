//! A 5 × 7 bitmap font for labels burned into contact sheets (no font
//! file, no shaping: the sheets must read the same on every machine).
//! Glyphs are column-major, bit 0 the top row; lowercase is drawn as
//! uppercase and anything unknown as `?`.

/// Each glyph's width and height in pixels, before the 1 px gap.
pub const W: u32 = 5;
pub const H: u32 = 7;

fn glyph(c: char) -> [u8; 5] {
    match c.to_ascii_uppercase() {
        ' ' => [0, 0, 0, 0, 0],
        '0' => [0x3E, 0x51, 0x49, 0x45, 0x3E],
        '1' => [0x00, 0x42, 0x7F, 0x40, 0x00],
        '2' => [0x42, 0x61, 0x51, 0x49, 0x46],
        '3' => [0x21, 0x41, 0x45, 0x4B, 0x31],
        '4' => [0x18, 0x14, 0x12, 0x7F, 0x10],
        '5' => [0x27, 0x45, 0x45, 0x45, 0x39],
        '6' => [0x3C, 0x4A, 0x49, 0x49, 0x30],
        '7' => [0x01, 0x71, 0x09, 0x05, 0x03],
        '8' => [0x36, 0x49, 0x49, 0x49, 0x36],
        '9' => [0x06, 0x49, 0x49, 0x29, 0x1E],
        'A' => [0x7E, 0x11, 0x11, 0x11, 0x7E],
        'B' => [0x7F, 0x49, 0x49, 0x49, 0x36],
        'C' => [0x3E, 0x41, 0x41, 0x41, 0x22],
        'D' => [0x7F, 0x41, 0x41, 0x22, 0x1C],
        'E' => [0x7F, 0x49, 0x49, 0x49, 0x41],
        'F' => [0x7F, 0x09, 0x09, 0x09, 0x01],
        'G' => [0x3E, 0x41, 0x49, 0x49, 0x7A],
        'H' => [0x7F, 0x08, 0x08, 0x08, 0x7F],
        'I' => [0x00, 0x41, 0x7F, 0x41, 0x00],
        'J' => [0x20, 0x40, 0x41, 0x3F, 0x01],
        'K' => [0x7F, 0x08, 0x14, 0x22, 0x41],
        'L' => [0x7F, 0x40, 0x40, 0x40, 0x40],
        'M' => [0x7F, 0x02, 0x1C, 0x02, 0x7F],
        'N' => [0x7F, 0x04, 0x08, 0x10, 0x7F],
        'O' => [0x3E, 0x41, 0x41, 0x41, 0x3E],
        'P' => [0x7F, 0x09, 0x09, 0x09, 0x06],
        'Q' => [0x3E, 0x41, 0x51, 0x21, 0x5E],
        'R' => [0x7F, 0x09, 0x19, 0x29, 0x46],
        'S' => [0x26, 0x49, 0x49, 0x49, 0x32],
        'T' => [0x01, 0x01, 0x7F, 0x01, 0x01],
        'U' => [0x3F, 0x40, 0x40, 0x40, 0x3F],
        'V' => [0x1F, 0x20, 0x40, 0x20, 0x1F],
        'W' => [0x3F, 0x40, 0x38, 0x40, 0x3F],
        'X' => [0x63, 0x14, 0x08, 0x14, 0x63],
        'Y' => [0x03, 0x04, 0x78, 0x04, 0x03],
        'Z' => [0x61, 0x59, 0x49, 0x4D, 0x43],
        '#' => [0x14, 0x7F, 0x14, 0x7F, 0x14],
        ':' => [0x00, 0x00, 0x24, 0x00, 0x00],
        '.' => [0x00, 0x40, 0x00, 0x00, 0x00],
        ',' => [0x00, 0x50, 0x30, 0x00, 0x00],
        '-' => [0x08, 0x08, 0x08, 0x08, 0x08],
        '+' => [0x08, 0x08, 0x3E, 0x08, 0x08],
        '=' => [0x14, 0x14, 0x14, 0x14, 0x14],
        '(' => [0x00, 0x1C, 0x22, 0x41, 0x00],
        ')' => [0x00, 0x41, 0x22, 0x1C, 0x00],
        '[' => [0x00, 0x7F, 0x41, 0x41, 0x00],
        ']' => [0x00, 0x41, 0x41, 0x7F, 0x00],
        '<' => [0x08, 0x14, 0x22, 0x41, 0x00],
        '>' => [0x00, 0x41, 0x22, 0x14, 0x08],
        '_' => [0x40, 0x40, 0x40, 0x40, 0x40],
        '/' => [0x20, 0x10, 0x08, 0x04, 0x02],
        '|' => [0x00, 0x00, 0x7F, 0x00, 0x00],
        '!' => [0x00, 0x00, 0x5F, 0x00, 0x00],
        '%' => [0x23, 0x13, 0x08, 0x64, 0x62],
        '"' => [0x00, 0x07, 0x00, 0x07, 0x00],
        '\'' => [0x00, 0x00, 0x07, 0x00, 0x00],
        '@' => [0x32, 0x49, 0x79, 0x41, 0x3E],
        '~' => [0x08, 0x04, 0x08, 0x10, 0x08],
        _ => [0x02, 0x01, 0x51, 0x09, 0x06],
    }
}

/// The width `text` takes.
pub fn width(text: &str) -> u32 {
    text.chars().count() as u32 * (W + 1)
}

/// Draws `text` into `rgba` (`w` × `h`) with its top left at `(x, y)`,
/// clipped to the image.
pub fn draw(rgba: &mut [u8], w: u32, h: u32, x: i64, y: i64, text: &str, color: [u8; 4]) {
    for (i, c) in text.chars().enumerate() {
        let gx = x + i as i64 * i64::from(W + 1);
        for (col, bits) in glyph(c).iter().enumerate() {
            for row in 0..H {
                if bits & (1 << row) == 0 {
                    continue;
                }
                let (px, py) = (gx + col as i64, y + i64::from(row));
                if px < 0 || py < 0 || px >= i64::from(w) || py >= i64::from(h) {
                    continue;
                }
                let at = ((py as u32 * w + px as u32) * 4) as usize;
                rgba[at..at + 4].copy_from_slice(&color);
            }
        }
    }
}
