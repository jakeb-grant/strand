/// The rows of `c`'s glyph.
pub(super) fn glyph(c: char) -> &'static [u8; H] {
    match c {
        ' '..='~' => &ASCII[c as usize - ' ' as usize],
        _ => &BOX,
    }
}

/// Splits `text` into at most `N` lines of at most `per_line`
/// characters, breaking at spaces (a word longer than a line is cut
/// across lines) and at line breaks; what does not fit is left out.
/// Each line is a slice of `text`, trimmed; `None` past the last.
pub(super) fn wrap<const N: usize>(text: &str, per_line: usize) -> [Option<&str>; N] {
    let mut out = [None; N];
    if per_line == 0 {
        return out;
    }
    let mut rest = text.trim();
    for slot in out.iter_mut() {
        rest = rest.trim_start();
        if rest.is_empty() {
            break;
        }
        // The end of what fits: the byte after `per_line` characters, or
        // the first line break before it.
        let mut fit = rest.len();
        let mut last_space = None;
        let mut cut = None;
        for (n, (i, c)) in rest.char_indices().enumerate() {
            if c == '\n' {
                cut = Some((i, i + 1));
                break;
            }
            if n == per_line {
                fit = i;
                break;
            }
            if c.is_whitespace() {
                last_space = Some(i);
            }
        }
        let (end, next) = match cut {
            Some(c) => c,
            None if fit == rest.len() => (fit, fit),
            // Past the end of the line: at its last space, unless the
            // character that does not fit is one.
            None if rest[fit..].starts_with(char::is_whitespace) => (fit, fit),
            None => match last_space {
                Some(s) => (s, s),
                None => (fit, fit),
            },
        };
        *slot = Some(rest[..end].trim_end());
        rest = &rest[next..];
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn printable_ascii_has_glyphs_and_the_rest_draws_a_box() {
        assert!(glyph(' ').iter().all(|r| *r == 0));
        assert_ne!(glyph('A'), &BOX);
        assert_eq!(glyph('é'), &BOX);
        assert_eq!(glyph('\u{7f}'), &BOX);
        for c in ' '..='~' {
            assert!(glyph(c).iter().all(|r| *r < 1 << W), "{c:?} is 5 wide");
        }
    }

    #[test]
    fn text_wraps_at_spaces_and_line_breaks() {
        let msg = "Place your finger on the fingerprint reader";
        assert_eq!(
            wrap::<3>(msg, 26),
            [
                Some("Place your finger on the"),
                Some("fingerprint reader"),
                None
            ]
        );
        assert_eq!(wrap::<3>("a\nb", 26), [Some("a"), Some("b"), None]);
        assert_eq!(
            wrap::<2>("abcdefgh ij", 4),
            [Some("abcd"), Some("efgh")],
            "a long word is cut; what does not fit is left out"
        );
        assert_eq!(wrap::<2>("ab cd", 2), [Some("ab"), Some("cd")]);
        assert_eq!(wrap::<2>("  ", 4), [None, None]);
        assert_eq!(wrap::<1>("éé é", 2), [Some("éé")], "by characters");
    }
}
