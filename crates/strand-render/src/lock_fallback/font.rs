//! (M6) The fallback lock's own type: a 5×7 bitmap of printable ASCII,
//! so PAM's text ("Place your finger on the fingerprint reader") shows
//! without the text worker, layout or fonts, any of which may be what
//! faulted. Each glyph is seven rows, top first, of five bits (the high
//! bit leftmost); a character it does not hold draws as a box.

/// Glyph columns and rows, in font pixels.
pub(super) const W: usize = 5;
pub(super) const H: usize = 7;

/// A character the font does not hold.
const BOX: [u8; H] = [
    0b11111, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11111,
];

