#!/usr/bin/env bash
# Tests scripts/eval/check-lock.sh on toy lock files.
# Run: scripts/container/run.sh bash scripts/eval/test-check-lock.sh

set -uo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
CHECK=$HERE/check-lock.sh
DIR=$(mktemp -d)
trap 'rm -rf "$DIR"' EXIT
bad=0

ok() { echo "ok   $1"; }
no() { echo "FAIL $1"; bad=1; }
# expect WANT NAME CMD...: CMD exits WANT.
expect() {
  local want=$1 name=$2 got=0
  shift 2
  "$@" >"$DIR/out" 2>&1 || got=$?
  if [ "$got" = "$want" ]; then ok "$name"; else no "$name: exit $got, wanted $want"; sed 's/^/     /' "$DIR/out"; fi
}
# lock FILE NAME=VERSION...: a Cargo.lock with those packages.
lock() {
  local f=$1
  shift
  printf '# This file is automatically @generated by Cargo.\nversion = 4\n' >"$f"
  for p in "$@"; do
    printf '\n[[package]]\nname = "%s"\nversion = "%s"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n' "${p%%=*}" "${p#*=}" >>"$f"
  done
}

lock "$DIR/root" serde=1.0.229 syn=1.0.109 syn=2.0.100 png=0.18.1
lock "$DIR/same" serde=1.0.229 syn=2.0.100
expect 0 "a subset at the root's versions passes" "$CHECK" "$DIR/root" "$DIR/same"

lock "$DIR/both" serde=1.0.229 syn=1.0.109 syn=2.0.100
expect 0 "two versions the root also locks pass" "$CHECK" "$DIR/root" "$DIR/both"

lock "$DIR/newer" serde=1.0.230 png=0.18.1
expect 1 "a newer version than the root's fails" "$CHECK" "$DIR/root" "$DIR/newer"
grep -q 'cargo update --manifest-path eval/Cargo.toml -p serde@1.0.230 --precise 1.0.229' "$DIR/out" &&
  ok "the failure names the fix" || no "the failure names the fix: $(cat "$DIR/out")"

lock "$DIR/third" serde=1.0.229 syn=3.0.0
expect 1 "a third version of a package the root locks twice fails" "$CHECK" "$DIR/root" "$DIR/third"

lock "$DIR/extra" serde=1.0.229 strand-eval=0.0.0
expect 0 "a package only eval/ has passes" "$CHECK" "$DIR/root" "$DIR/extra"
grep -q 'only in eval/Cargo.lock: strand-eval 0.0.0' "$DIR/out" &&
  ok "and is listed" || no "and is listed: $(cat "$DIR/out")"

expect 2 "a missing lock file is an error" "$CHECK" "$DIR/root" "$DIR/nothing"

expect 0 "this checkout's eval/Cargo.lock agrees with its Cargo.lock" "$CHECK"

[ "$bad" = 0 ] && echo "test-check-lock: all passed"
exit "$bad"
